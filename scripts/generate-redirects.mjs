#!/usr/bin/env node
/**
 * Rewrites the generated redirect blocks in `public/.htaccess` and
 * `public/_redirects` from `src/data/legacy-redirects.json`.
 *
 * `output: "export"` means `next.config.ts` redirects are unsupported, so every
 * 301 has to live in the static host's own config. Keeping both files generated
 * from one JSON stops Apache and Netlify/Cloudflare drifting apart.
 *
 *   node scripts/generate-redirects.mjs          # write
 *   node scripts/generate-redirects.mjs --check  # fail if out of date (CI)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = resolve(root, "src/data/legacy-redirects.json");
const htaccessPath = resolve(root, "public/.htaccess");
const netlifyPath = resolve(root, "public/_redirects");

const BEGIN = "# BEGIN majd:legacy-redirects";
const END = "# END majd:legacy-redirects";
const GENERATED_BY =
  "generated by scripts/generate-redirects.mjs from src/data/legacy-redirects.json — do not edit by hand";

const { redirects } = JSON.parse(readFileSync(dataPath, "utf8"));

/** Percent-encode a decoded path, leaving the slashes intact. */
function encodePath(path) {
  return path
    .split("/")
    .map((segment) => encodeURIComponent(segment))
    .join("/");
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** `/services/x/` → `services/x` (mod_rewrite per-dir patterns are root-relative) */
function relative(path) {
  return path.replace(/^\/+/, "").replace(/\/+$/, "");
}

function htaccessBlock() {
  const lines = [
    BEGIN,
    `# ${GENERATED_BY}`,
    "#",
    "# Apache decodes the request URI before matching, so the REQUEST_URI condition",
    "# carries the literal Persian path and the THE_REQUEST condition covers hosts",
    "# that hand mod_rewrite the raw percent-encoded request line. NE keeps the",
    "# already-encoded target from being escaped a second time.",
  ];

  for (const { from, to, reason } of redirects) {
    const decoded = escapeRegex(relative(from));
    const encoded = escapeRegex(relative(encodePath(from)));
    lines.push(
      "",
      `# ${reason}`,
      `# ${from} → ${to}`,
      `RewriteCond %{REQUEST_URI} ^/${decoded}/?$ [OR]`,
      `RewriteCond %{THE_REQUEST} \\s/${encoded}/?[\\s?]`,
      `RewriteRule ^ ${encodePath(to)} [R=301,L,NE]`,
    );
  }

  lines.push("", END);
  return lines.join("\n");
}

function netlifyBlock() {
  const lines = [BEGIN, `# ${GENERATED_BY}`];

  for (const { from, to, reason } of redirects) {
    const encodedFrom = encodePath(from);
    lines.push("", `# ${reason}`, `${from}    ${to}    301`);
    if (encodedFrom !== from) {
      lines.push(`${encodedFrom}    ${to}    301`);
    }
  }

  lines.push("", END);
  return lines.join("\n");
}

/** Replace an existing marker block, or prepend/insert a new one. */
function applyBlock(source, block, insertAfter) {
  const begin = source.indexOf(BEGIN);
  const end = source.indexOf(END);

  if (begin !== -1 && end !== -1) {
    return source.slice(0, begin) + block + source.slice(end + END.length);
  }

  if (insertAfter) {
    const anchor = source.indexOf(insertAfter);
    if (anchor === -1) {
      throw new Error(`Anchor not found in target file: ${insertAfter}`);
    }
    const at = anchor + insertAfter.length;
    return `${source.slice(0, at)}\n\n${block}\n${source.slice(at)}`;
  }

  return `${block}\n\n${source}`;
}

const check = process.argv.includes("--check");
let stale = false;

for (const [path, block, insertAfter] of [
  [htaccessPath, htaccessBlock(), "  RewriteBase /"],
  [netlifyPath, netlifyBlock(), null],
]) {
  const current = readFileSync(path, "utf8");
  const next = applyBlock(current, block, insertAfter);

  if (current === next) {
    console.log(`up to date: ${path}`);
    continue;
  }

  if (check) {
    stale = true;
    console.error(`out of date: ${path}`);
    continue;
  }

  writeFileSync(path, next, "utf8");
  console.log(`written: ${path}`);
}

if (stale) {
  console.error("\nRun `npm run generate:redirects` and commit the result.");
  process.exit(1);
}
