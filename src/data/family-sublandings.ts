const bySlug = new Map(familySublandings.map((item) => [item.slug, item]));

export function familySublandingCopy(
  slug: string,
): FamilySublandingCopy | undefined {
  return bySlug.get(slug);
}

export function plainContentLength(html: string | undefined): number {
  return (html ?? "").replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim()
    .length;
}

export function familySublandingService(slug: string): Service | null {
  const copy = familySublandingCopy(slug);
  if (!copy) return null;
  return {
    id: `family-${copy.slug}`,
    slug: copy.slug,
    title: copy.cardTitle,
    pageTitle: copy.headline,
    excerpt: copy.cardExcerpt,
    description: copy.hero,
    icon: copy.icon,
    hubSlug: "family-lawyer",
    categoryPrefix: "family-lawyer",
    parentSlug: "family-lawyer",
    parentTitle: "وکیل خانواده",
    contentHtml: copy.html,
    keywords: copy.keywords,
  };
}

