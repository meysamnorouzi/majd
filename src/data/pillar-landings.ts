function normalizeKey(value: string): string {
  let current = value.trim();
  for (let i = 0; i < 3; i++) {
    try {
      const decoded = decodeURIComponent(current);
      if (decoded === current) break;
      current = decoded;
    } catch {
      break;
    }
  }
  return current.toLowerCase().replace(/_/g, "-");
}

function titleHasPhrase(title: string, needle: string): boolean {
  if (!needle || !title.includes(needle)) return false;
  const escaped = needle.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(
    `(^|[^\\u0600-\\u06FFa-zA-Z0-9])${escaped}([^\\u0600-\\u06FFa-zA-Z0-9]|$)`,
  );
  return re.test(title);
}

function cardMatchScore(
  card: Service,
  copy: PillarLandingCardCopy,
): number {
  const slug = normalizeKey(card.slug);
  if (copy.slugs.some((item) => slug === normalizeKey(item))) return 300;
  if (normalizeKey(card.title) === normalizeKey(copy.title)) return 200;
  if (card.title.startsWith(copy.title)) return 150;
  if (!copy.titleIncludes.some((needle) => titleHasPhrase(card.title, needle))) {
    return 0;
  }
  let score = 80 - Math.min(card.title.length, 50);
  if (card.title.startsWith("وکیل")) score += 25;
  else if (card.title.includes("وکیل")) score += 10;
  return Math.max(1, score);
}

/**
 * Overlay hub card titles/excerpts for the landing services.
 * When copy matches, only those featured cards are returned so the hub
 * stays aligned with the landing outline instead of listing every WP leaf.
 */
export function applyPillarLandingCards(
  cards: Service[],
  landing: PillarLanding | undefined,
): Service[] {
  if (!landing?.cardCopy.length) return cards.slice(0, 6);

  const remaining = [...cards];
  const ordered: Service[] = [];

  for (const copy of landing.cardCopy) {
    let bestIndex = -1;
    let bestScore = 0;
    remaining.forEach((card, index) => {
      const score = cardMatchScore(card, copy);
      if (score > bestScore) {
        bestScore = score;
        bestIndex = index;
      }
    });
    if (bestIndex === -1) continue;
    const [matched] = remaining.splice(bestIndex, 1);
    if (!matched) continue;
    ordered.push({
      ...matched,
      title: copy.title,
      excerpt: copy.excerpt,
    });
  }

  return ordered.length ? ordered : cards.slice(0, 6);
}
